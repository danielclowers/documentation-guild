const pixels = Object.fromEntries(
  Object.entries(glyphs).map(([name, rows]) => [
    name,
    rows
      .flatMap((row, y) =>
        [...row].flatMap((value, x) => (value === '1' ? `${x * 2}px ${y * 2}px currentColor` : [])),
      )
      .join(', '),
  ]),
);

export type IconName = keyof typeof glyphs;

export function GameIcon({ name }: { name: IconName }) {
  return (
    <span
      className="game-icon"
      aria-hidden="true"
      style={{ '--pixels': pixels[name] } as CSSProperties}
    />
  );
}
